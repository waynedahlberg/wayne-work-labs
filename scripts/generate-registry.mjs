#!/usr/bin/env node
// Scans /labs/*/lab.ts and writes the two generated registry files.
// Runs before `dev` and `build` (see package.json) and from `labs:check`.
import { readdirSync, statSync, existsSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const labsDir = path.join(root, "labs");
const outDir = path.join(root, "features/labs");

const slugs = existsSync(labsDir)
  ? readdirSync(labsDir)
      .filter((d) => statSync(path.join(labsDir, d)).isDirectory())
      .filter((d) => existsSync(path.join(labsDir, d, "lab.ts")))
      .sort()
  : [];

const ident = (slug) => "lab_" + slug.replace(/[^a-zA-Z0-9]/g, "_");
const banner = "// AUTO-GENERATED by scripts/generate-registry.mjs. Do not edit.\n";

const meta =
  banner +
  `import type { LabMeta } from "./types";\n` +
  slugs.map((s) => `import ${ident(s)} from "@/labs/${s}/lab";`).join("\n") +
  `\n\nexport const allLabs: LabMeta[] = [${slugs.map(ident).join(", ")}];\n`;

const withDemo = slugs.filter((s) => existsSync(path.join(labsDir, s, "Demo.tsx")));
const demos =
  banner +
  `"use client";\n\nimport { lazy, type ComponentType } from "react";\nimport type { DemoProps } from "./types";\n\n` +
  `export const demos: Record<string, ComponentType<DemoProps>> = {\n` +
  withDemo
    .map((s) => `  "${s}": lazy(() => import("@/labs/${s}/Demo")),`)
    .join("\n") +
  `\n};\n`;

writeFileSync(path.join(outDir, "registry.generated.ts"), meta);
writeFileSync(path.join(outDir, "demos.generated.tsx"), demos);
console.log(`labs registry: ${slugs.length} lab(s)`);
